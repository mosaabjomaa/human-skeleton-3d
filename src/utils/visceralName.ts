export function formatVisceralName(name: string, language: string) {
  const cleanName = name.replace(/\.j$|\.r$|\.l$/i, "").replaceAll("_", " ");
  if (language !== "ar") return cleanName;
  const exact = arabicNames[name];
  if (exact) return exact;
  return cleanName
    .split(/(\s+|[().,+])/)
    .map((part) => words[part.toLowerCase()] ?? part)
    .join("")
    .replace(/\s+/g, " ")
    .trim();
}
